-- 기존 회원은 기본 USER 권한을 갖도록 보완한 뒤, 게시글과 댓글 테이블을 생성합니다.
ALTER TABLE members ADD COLUMN role varchar(20) NOT NULL DEFAULT 'USER';

CREATE TABLE boards (
	id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
	title varchar(100) NOT NULL,
	content text NOT NULL,
	view_count bigint NOT NULL,
	notice boolean NOT NULL,
	author_id bigint NOT NULL,
	created_at timestamp(6) NOT NULL,
	updated_at timestamp(6) NOT NULL,
	PRIMARY KEY (id),
	CONSTRAINT fk_boards_author FOREIGN KEY (author_id) REFERENCES members (id)
);

CREATE TABLE comments (
	id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
	content text NOT NULL,
	board_id bigint NOT NULL,
	author_id bigint NOT NULL,
	created_at timestamp(6) NOT NULL,
	updated_at timestamp(6) NOT NULL,
	PRIMARY KEY (id),
	CONSTRAINT fk_comments_board FOREIGN KEY (board_id) REFERENCES boards (id),
	CONSTRAINT fk_comments_author FOREIGN KEY (author_id) REFERENCES members (id)
);

-- 공지 우선·최신순 목록과 게시글별 시간순 댓글 조회에 사용하는 인덱스입니다.
CREATE INDEX idx_boards_notice_created_at ON boards (notice DESC, created_at DESC);
CREATE INDEX idx_comments_board_created_at ON comments (board_id, created_at ASC);
