-- 프론트 이미지와 별개로 실제 예약할 서비스 분류·방문 정보·관리 처리 상태를 영속화합니다.
CREATE TABLE reservations (
	id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
	service_category varchar(30) NOT NULL,
	scheduled_at timestamp(6) NOT NULL,
	address varchar(200) NOT NULL,
	contact_name varchar(30) NOT NULL,
	contact_phone varchar(20) NOT NULL,
	request_note text,
	status varchar(20) NOT NULL,
	member_id bigint NOT NULL,
	created_at timestamp(6) NOT NULL,
	updated_at timestamp(6) NOT NULL,
	PRIMARY KEY (id),
	CONSTRAINT fk_reservations_member FOREIGN KEY (member_id) REFERENCES members (id)
);

-- 회원별 내역과 관리자 최신 요청 목록을 빠르게 조회하도록 예약자·생성 시각 조합 인덱스를 둡니다.
CREATE INDEX idx_reservations_member_created_at ON reservations (member_id, created_at DESC);
CREATE INDEX idx_reservations_created_at ON reservations (created_at DESC);
