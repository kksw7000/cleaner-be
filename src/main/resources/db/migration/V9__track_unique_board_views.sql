-- 게시글별 방문자를 한 번만 저장해 재방문 조회수 증가를 방지합니다.
CREATE TABLE board_views (
	id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
	board_id bigint NOT NULL,
	viewer_key varchar(80) NOT NULL,
	PRIMARY KEY (id),
	CONSTRAINT fk_board_views_board FOREIGN KEY (board_id) REFERENCES boards (id) ON DELETE CASCADE,
	CONSTRAINT uk_board_views_board_viewer UNIQUE (board_id, viewer_key)
);
