CREATE TABLE notifications (
	id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
	member_id bigint NOT NULL,
	reservation_id bigint,
	type varchar(40) NOT NULL,
	message varchar(200) NOT NULL,
	created_at timestamp(6) NOT NULL,
	read_at timestamp(6),
	PRIMARY KEY (id),
	CONSTRAINT fk_notifications_member FOREIGN KEY (member_id) REFERENCES members (id) ON DELETE CASCADE,
	CONSTRAINT fk_notifications_reservation FOREIGN KEY (reservation_id) REFERENCES reservations (id) ON DELETE SET NULL
);

CREATE INDEX idx_notifications_member_created_at ON notifications (member_id, created_at DESC, id DESC);
CREATE INDEX idx_notifications_member_read_at ON notifications (member_id, read_at);
